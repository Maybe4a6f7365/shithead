import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import path from 'node:path'

const here = path.dirname(fileURLToPath(import.meta.url))
const commit = process.env.WORKERS_CI_COMMIT_SHA || process.env.GITHUB_SHA || 'local'

// 1. Worker build metadata (served by /api/version).
const target = path.resolve(here, '../src/worker/build-meta.ts')
await mkdir(path.dirname(target), { recursive: true })
await writeFile(
  target,
  `// Generated by scripts/write-build-meta.mjs.\nexport const BUILD_COMMIT = ${JSON.stringify(commit)}\n`,
  'utf8',
)

// 2. Stamp the same commit into index.html so the deployed UI can be
//    tied back to a commit (verified by scripts/smoke-multiplayer.mjs).
const indexPath = path.resolve(here, '../index.html')
const indexHtml = await readFile(indexPath, 'utf8')
const stamped = indexHtml.replace(
  /(<meta name="build-commit" content=")[^"]*("\s*\/>)/,
  `$1${commit}$2`,
)
if (stamped === indexHtml && !indexHtml.includes(`content="${commit}"`)) {
  throw new Error('index.html is missing the <meta name="build-commit"> tag')
}
await writeFile(indexPath, stamped, 'utf8')

console.log(`Worker build commit: ${commit}`)
