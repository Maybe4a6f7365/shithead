import { mkdir, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import path from 'node:path'

const here = path.dirname(fileURLToPath(import.meta.url))
const target = path.resolve(here, '../src/worker/build-meta.ts')
const commit = process.env.WORKERS_CI_COMMIT_SHA || process.env.GITHUB_SHA || 'local'

await mkdir(path.dirname(target), { recursive: true })
await writeFile(
  target,
  `// Generated by scripts/write-build-meta.mjs.\nexport const BUILD_COMMIT = ${JSON.stringify(commit)}\n`,
  'utf8',
)

console.log(`Worker build commit: ${commit}`)
